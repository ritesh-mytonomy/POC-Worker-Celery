-- ── Reference masters ───────────────────────────────────────────────────────

CREATE TABLE specialty (                                         -- [LLD] [deferred]
  specialty_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(64)  NOT NULL UNIQUE,
  display_name  VARCHAR(255) NOT NULL,
  is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE document_type (                                     -- [LLD] [deferred]
  document_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(64)  NOT NULL UNIQUE,
  display_name     VARCHAR(255) NOT NULL,
  is_active        BOOLEAN      NOT NULL DEFAULT TRUE
);

-- organization_specialty and organization_document_type: [deferred] with metadata tagging.


-- ── M2 · The library ────────────────────────────────────────────────────────
-- Created before the upload tables, because upload_file.replaces_document_id
-- and staged_document.duplicate_of_document_id point here. The reverse link,
-- documents.source_file_id, is added once upload_file exists (bottom of file).

CREATE TABLE documents (                                         -- [LLD]
  document_id          UUID         PRIMARY KEY,                 -- uuid5 of the candidate: a re-run commit reuses it
  organization_id      UUID         NOT NULL REFERENCES organizations(id),
  title                VARCHAR(512) NOT NULL,
  title_norm           VARCHAR(512) NOT NULL,                    -- lower-cased, punctuation-stripped
  file_name            VARCHAR(512) NOT NULL,                    -- original name of the current version
  file_name_norm       VARCHAR(512) NOT NULL,                    -- casefolded, trimmed — the name+size check
  document_type_id     BIGINT       REFERENCES document_type(document_type_id),   -- [deferred] null = untagged
  current_version      INTEGER      NOT NULL DEFAULT 1,          -- replace is out of scope: always 1 here
  s3_key               VARCHAR(1024) NOT NULL,                   -- ClinSync/processed/{org}/{document_id}/v{n}_{file_name}
  file_ext             VARCHAR(10)  NOT NULL,
  size_bytes           BIGINT       NOT NULL,
  content_hash         CHAR(64)     NOT NULL,                    -- SHA-256, computed by the worker
  source_file_id       UUID,                                     -- FK added below; provenance only
  video_script_seq     INTEGER,
  status               VARCHAR(16)  NOT NULL DEFAULT 'active'
                         CHECK (status IN ('active', 'archived')),
  added_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
  version_uploaded_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  version_uploaded_by  BIGINT       NOT NULL,                    -- AUTH user id; POC_USER_ID until auth exists
  last_scanned_at      TIMESTAMPTZ,                              -- [deferred] scan
  last_scan_id         UUID,                                     -- [deferred] FK to scan_run when M3 lands
  highest_risk         VARCHAR(16)
                         CHECK (highest_risk IN ('HIGH', 'MEDIUM', 'LOW', 'CONFIRMATORY')),
  open_findings        INTEGER      NOT NULL DEFAULT 0,
  CONSTRAINT uq_org_title UNIQUE (organization_id, title_norm)
);
CREATE INDEX idx_doc_org_hash      ON documents (organization_id, content_hash);
CREATE INDEX idx_doc_org_filename  ON documents (organization_id, file_name_norm);
CREATE INDEX idx_doc_org_scanned   ON documents (organization_id, last_scanned_at);
CREATE TRIGGER trg_doc_updated BEFORE UPDATE ON documents
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE document_specialty (                                -- [LLD M3.2] [deferred]
  document_id   UUID   NOT NULL REFERENCES documents(document_id) ON DELETE CASCADE,
  specialty_id  BIGINT NOT NULL REFERENCES specialty(specialty_id),
  PRIMARY KEY (document_id, specialty_id)
);

