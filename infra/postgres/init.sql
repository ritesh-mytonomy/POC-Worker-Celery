-- ════════════════════════════════════════════════════════════════════════════
-- ClinSync — upload + ingest merge · PostgreSQL 15+
-- Follows the LLD data model: M1 organization tables, M2.1 upload and library
-- tables, M2.5 state machines, M3.2 document_specialty.
--
-- Markers used below:
--   [LLD]      exactly as the LLD defines it
--   [POC]      added by the Ingest Worker POC — needed for claim, resume, retry;
--              to be folded back into the LLD
--   [Anugrah]  needed by the File Upload POC's API
--   [deferred] in the LLD, but out of this merge's scope — created, unused
--
-- Primary keys are UUID throughout, per OD-18's recommendation.
-- Reference masters (specialty, document_type) stay BIGINT, as the LLD has them.
-- ════════════════════════════════════════════════════════════════════════════

CREATE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$ LANGUAGE plpgsql;                                             -- [LLD]


-- ── M1 · Organizations ──────────────────────────────────────────────────────
-- Auth is out of scope, but every organization_id is a foreign key into this
-- table, so it exists and holds the one POC organization.

CREATE TABLE organizations (                                     -- [LLD]
  id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  name        VARCHAR     NOT NULL UNIQUE,
  is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_org_updated BEFORE UPDATE ON organizations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

